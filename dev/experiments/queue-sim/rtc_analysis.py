"""Tables and decision rules R1-R4 of PREREG-run-to-completion.md from results/rtc.csv -> results/rtc_tables.md."""
import csv
import os
import random
import statistics as st
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
LATE_KEYS = ["late_h_10_12", "late_h_12_15", "late_h_15_20", "late_h_20_30", "late_h_30_60", "late_h_60_120",
             "late_h_120_inf"]


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def index(rows):
    """{(band, tail, dispatch, arm): {cfg_i: row}}"""
    ix = defaultdict(dict)
    for r in rows:
        ix[(r["band"], r["tail"], r["dispatch"], r["arm"])][r["cfg_i"]] = r
    return ix


def pair(ix, band, tail, disp, a, b, key):
    ra, rb = ix[(band, tail, disp, a)], ix[(band, tail, disp, b)]
    ks = sorted(set(ra) & set(rb), key=lambda k: int(k))
    return [f(ra[k][key]) for k in ks], [f(rb[k][key]) for k in ks]


def paired_ci(a, b, n=2000, seed=1):
    """(lo, mean, hi) of mean(a - b): 95 % bootstrap over configurations."""
    d = [x - y for x, y in zip(a, b) if x == x and y == y]
    m = sum(d) / len(d)
    r = random.Random(seed)
    bs = sorted(sum(r.choice(d) for _ in d) / len(d) for _ in range(n))
    return bs[int(0.025 * n)], m, bs[int(0.975 * n) - 1]


def vals(ix, band, tail, disp, arm, key):
    return [f(r[key]) for r in ix[(band, tail, disp, arm)].values() if f(r[key]) == f(r[key])]


def mean(v):
    return sum(v) / len(v) if v else float("nan")


def med(v):
    return st.median(v) if v else float("nan")


def pc(x, d=3):
    return "—" if x != x else f"{100 * x:.{d}f} %"


def ms(x):
    return "—" if x != x else (f"{1000 * x:.0f} ms" if x < 1 else f"{x:.2f} s")


def table(out, head, rows):
    out.append("| " + " | ".join(head) + " |")
    out.append("|" + " --- |" * len(head))
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    out.append("")


def arms_table(out, ix, band, tail, disp, arms):
    head = ["arm", "ok", "busy", "abandoned", "fail", "ok p50", "ok p95", "ok p99", "ok p99.9", "late / ok",
            "> 30 s / calls", "goodput /s", "abandoned permit-s / 1k", "turns failed", "ttd p99"]
    rows = []
    for a in arms:
        if not ix[(band, tail, disp, a)]:
            continue
        v = lambda k: vals(ix, band, tail, disp, a, k)  # noqa: E731
        rows.append([a, pc(mean(v("ok_rate"))), pc(mean(v("refuse_rate"))), pc(mean(v("timeout_rate"))),
                     pc(mean(v("fail_rate"))), ms(med(v("ok_p50"))), ms(med(v("ok_p95"))), ms(med(v("ok_p99"))),
                     ms(med(v("ok_p999"))), pc(mean(v("ok_late_share"))), pc(mean(v("ok_late30_rate")), 4),
                     f"{mean(v('goodput_per_s')):.2f}", f"{mean(v('ab_permit_s_per_kcall')):.1f}",
                     pc(mean(v("turn_failed"))), ms(med(v("ttd_p99")))])
    table(out, head, rows)


def ci_s(ci, d=3):
    lo, m, hi = ci
    return f"{100 * m:+.{d}f} pp [{100 * lo:+.{d}f}, {100 * hi:+.{d}f}]"


def main(path):
    rows = [r for r in csv.DictReader(open(path))]
    ix = index(rows)
    arms = list(dict.fromkeys(r["arm"] for r in rows))
    bands = [b for b in ("realistic", "stress") if any(k[0] == b for k in ix)]
    out = ["# Run-to-completion study tables (generated by rtc_analysis.py; PREREG-run-to-completion.md)", ""]
    out.append(f"{len(rows)} simulations; configurations per band: "
               + ", ".join(f"{b} {len(ix[(b, 'base', 'P2', 'old_p90')])}" for b in bands) + ".")
    out.append("Rates are means over configurations; latency percentiles are medians over configurations of the "
               "per-configuration value. pp = percentage points; intervals are 95 % paired bootstrap.\n")

    # ------------------------------------------------------------ R1
    out.append("## R1. Start check: p90 against wait-only, run limit 60 s\n")
    head = ["band", "tail", "dispatch", "ΔF p90 − wait", "Δ busy", "Δ abandoned", "ttd p99 ratio wait/p90 (median)",
            "wait: late / ok", "wait: > 30 s / calls"]
    r1 = []
    res = {}
    for b in bands:
        for t in ("base", "long"):
            for d in ("P2", "P0"):
                ci = paired_ci(*pair(ix, b, t, d, "rtc_p90_rl60", "rtc_wait_rl60", "fail_rate"))
                cb = paired_ci(*pair(ix, b, t, d, "rtc_p90_rl60", "rtc_wait_rl60", "refuse_rate"))
                ca = paired_ci(*pair(ix, b, t, d, "rtc_p90_rl60", "rtc_wait_rl60", "timeout_rate"))
                xw, xp = pair(ix, b, t, d, "rtc_wait_rl60", "rtc_p90_rl60", "ttd_p99")
                ratio = med([w / p for w, p in zip(xw, xp) if p > 0 and w == w])
                late = mean(vals(ix, b, t, d, "rtc_wait_rl60", "ok_late_share"))
                late30 = mean(vals(ix, b, t, d, "rtc_wait_rl60", "ok_late30_rate"))
                res[(b, t, d)] = (ci, ratio, late, late30)
                r1.append([b, t, d, ci_s(ci), ci_s(cb), ci_s(ca), f"{ratio:.3f}", pc(late), pc(late30, 4)])
    table(out, head, r1)
    ci, ratio, _, _ = res[("realistic", "base", "P2")]
    guard = all(res[("realistic", t, "P2")][2] <= 0.01 and res[("realistic", t, "P2")][3] <= 0.001
                for t in ("base", "long"))
    c1 = not ci[2] < 0
    c2 = ratio <= 1.10
    if not guard:
        verdict = "REPORT TO OWNER: the late-answer guard (condition 3) fails"
        chk = "p90"
    elif c1 and c2:
        verdict = "DROP the p90 check: start any call that gets a permit before its wait deadline"
        chk = "wait"
    else:
        verdict = "KEEP the p90 check"
        chk = "p90"
    out.append(f"**R1 verdict:** {verdict}. Deciding cell realistic/base/P2: ΔF {ci_s(ci)} (condition 1 "
               f"{'holds' if c1 else 'fails'}), ttd p99 ratio {ratio:.3f} (condition 2 {'holds' if c2 else 'fails'}), "
               f"late-answer guard {'holds' if guard else 'fails'}.")
    flips = [k for k, (c, *_) in res.items() if k != ("realistic", "base", "P2") and
             ((c[1] > 0) != (ci[1] > 0)) and (c[0] > 0 or c[2] < 0)]
    out.append("Cells pointing the other way (sign differs, interval excludes 0): "
               + (", ".join("/".join(k) for k in flips) if flips else "none") + ".\n")

    # ------------------------------------------------------------ R2
    out.append(f"## R2. Run limit: run-limit hits (abandoned after start) with the {chk} check\n")
    head = ["band", "tail", "dispatch", "rl 30 s", "rl 60 s", "rl 120 s", "abandoned permit-s / 1k at 60 s"]
    r2 = []
    for b in bands:
        for t in ("base", "long"):
            for d in ("P2", "P0"):
                hits = [mean(vals(ix, b, t, d, f"rtc_{chk}_rl{rl}", "timeout_rate")) for rl in (30, 60, 120)]
                r2.append([b, t, d, *(pc(h, 4) for h in hits),
                           f"{mean(vals(ix, b, t, d, f'rtc_{chk}_rl60', 'ab_permit_s_per_kcall')):.1f}"])
    table(out, head, r2)
    rl_pick = None
    for rl in (30, 60, 120):
        hb = mean(vals(ix, "realistic", "base", "P2", f"rtc_{chk}_rl{rl}", "timeout_rate"))
        hl = mean(vals(ix, "realistic", "long", "P2", f"rtc_{chk}_rl{rl}", "timeout_rate"))
        if hb <= 1e-4 and hl <= 5e-4:
            rl_pick = rl
            break
    out.append(f"**R2 verdict:** run_limit_ms = {(rl_pick or 120) * 1000}"
               + ("" if rl_pick else " (no limit met the rule; reported to the owner)") + ".\n")
    rl = rl_pick or 120

    # ------------------------------------------------------------ Q1
    out.append("## Q1. Former timeouts under the old rule, and what run to completion makes of them\n")
    head = ["band", "tail", "dispatch", "old: abandoned", "old: late-admit abandoned", "rtc: late ok / calls",
            "rtc: late-start ok", f"rtc: run-limit hits ({rl} s)", "rtc: busy", "old: busy"]
    q1 = []
    hist = defaultdict(lambda: [0] * len(LATE_KEYS))
    for b in bands:
        for t in ("base", "long"):
            for d in ("P2", "P0"):
                a = f"rtc_{chk}_rl{rl}"
                q1.append([b, t, d, pc(mean(vals(ix, b, t, d, "old_p90", "timeout_rate"))),
                           pc(mean(vals(ix, b, t, d, "old_p90", "late_admit_timeout_rate"))),
                           pc(mean(vals(ix, b, t, d, a, "ok_late_rate"))),
                           pc(mean(vals(ix, b, t, d, a, "late_start_ok_rate"))),
                           pc(mean(vals(ix, b, t, d, a, "timeout_rate")), 4),
                           pc(mean(vals(ix, b, t, d, a, "refuse_rate"))),
                           pc(mean(vals(ix, b, t, d, "old_p90", "refuse_rate")))])
                for r in ix[(b, t, d, a)].values():
                    for j, k in enumerate(LATE_KEYS):
                        hist[(b, t, d)][j] += int(f(r[k]))
    table(out, head, q1)
    out.append(f"Lateness of late successes, rtc_{chk}_rl{rl} (pooled counts over configurations):\n")
    table(out, ["band", "tail", "dispatch", "(10,12] s", "(12,15]", "(15,20]", "(20,30]", "(30,60]", "(60,120]",
                "> 120"], [[*k, *v] for k, v in hist.items()])

    # ------------------------------------------------------------ R3
    out.append(f"## R3. Queue depth and head-of-line: old_p90 against rtc_{chk}_rl{rl}\n")
    head = ["band", "tail", "Δ queue_full (rtc − old, P2)", "max_queue ≥ 32: old / rtc (P2)",
            "P0 − P2 fail: old", "P0 − P2 fail: rtc", "P0 − P2 ok p99: old", "P0 − P2 ok p99: rtc"]
    r3 = []
    changed = []
    a = f"rtc_{chk}_rl{rl}"
    for b in bands:
        for t in ("base", "long"):
            dq = paired_ci(*pair(ix, b, t, "P2", a, "old_p90", "rf_queue_full"))
            mq = [mean([1.0 if f(x) >= 32 else 0.0 for x in vals(ix, b, t, "P2", arm, "max_queue")])
                  for arm in ("old_p90", a)]
            ex = {}
            for arm in ("old_p90", a):
                x0 = {k: f(r["fail_rate"]) for k, r in ix[(b, t, "P0", arm)].items()}
                x2 = {k: f(r["fail_rate"]) for k, r in ix[(b, t, "P2", arm)].items()}
                ks = sorted(set(x0) & set(x2), key=int)
                ex[arm] = paired_ci([x0[k] for k in ks], [x2[k] for k in ks])
            lat = {}
            for arm in ("old_p90", a):
                x0 = {k: f(r["ok_p99"]) for k, r in ix[(b, t, "P0", arm)].items()}
                x2 = {k: f(r["ok_p99"]) for k, r in ix[(b, t, "P2", arm)].items()}
                lat[arm] = med([x0[k] - x2[k] for k in set(x0) & set(x2) if x0[k] == x0[k] and x2[k] == x2[k]])
            ch = (abs(dq[1]) > 0.001 or mq[1] - mq[0] > 0.01 or abs(ex[a][1] - ex["old_p90"][1]) > 0.0005
                  or (lat["old_p90"] and abs(lat[a] - lat["old_p90"]) > 0.25 * abs(lat["old_p90"])))
            if ch:
                changed.append(f"{b}/{t}")
            r3.append([b, t, ci_s(dq), f"{pc(mq[0], 1)} / {pc(mq[1], 1)}", ci_s(ex["old_p90"]), ci_s(ex[a]),
                       ms(lat["old_p90"]), ms(lat[a])])
    table(out, head, r3)
    out.append("**R3 verdict:** run to completion changes the depth or head-of-line result in: "
               + (", ".join(changed) if changed else "no band or tail") + ".\n")

    # ------------------------------------------------------------ R4
    out.append(f"## R4. EP-09: the {chk} check with an interrupting run limit\n")
    head = ["band", "tail", "dispatch", "arm", "fail", "busy", "interrupted", "late / ok", "ok p99", "ok p99.9",
            "abandoned permit-s / 1k"]
    r4 = []
    for b in bands:
        for t in ("base", "long"):
            for d in ("P2", "P0"):
                for arm in (f"rtc_{chk}_rl60", f"rtc_{chk}_ep09_rl10", f"rtc_{chk}_ep09_rl30", f"rtc_{chk}_ep09_rl60",
                            "old_p90_ep09"):
                    v = lambda k: vals(ix, b, t, d, arm, k)  # noqa: E731
                    r4.append([b, t, d, arm, pc(mean(v("fail_rate"))), pc(mean(v("refuse_rate"))),
                               pc(mean(v("timeout_rate"))), pc(mean(v("ok_late_share"))), ms(med(v("ok_p99"))),
                               ms(med(v("ok_p999"))), f"{mean(v('ab_permit_s_per_kcall')):.1f}"])
    table(out, head, r4)
    ref = {t: mean(vals(ix, "realistic", t, "P2", f"rtc_{chk}_ep09_rl60", "fail_rate")) for t in ("base", "long")}
    pick = 60
    for r in (10, 30, 60):
        if all(mean(vals(ix, "realistic", t, "P2", f"rtc_{chk}_ep09_rl{r}", "fail_rate")) - ref[t] <= 0.0001
               for t in ("base", "long")):
            pick = r
            break
    out.append(f"**R4 verdict:** with EP-09, run_limit_ms can come down to {pick * 1000}.\n")

    # ------------------------------------------------------------ all arms
    out.append("## All arms\n")
    for b in bands:
        for t in ("base", "long"):
            for d in ("P2", "P0"):
                out.append(f"### {b}, {t} tail, {d}\n")
                arms_table(out, ix, b, t, d, arms)
    open(os.path.join(RES, "rtc_tables.md"), "w").write("\n".join(out))
    print("\n".join(x for x in out if x.startswith("**")))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(RES, "rtc.csv"))
