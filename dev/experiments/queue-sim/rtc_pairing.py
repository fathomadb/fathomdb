"""Per-call fate of the old rule's timeouts under run to completion (REPORT § 12.3 Q1).

usage: python rtc_pairing.py [n_real]  -> results/rtc_pairing.md (+ streamed results/rtc_pairing.jsonl)
Common random numbers give each client's i-th call the same kind and service times in every arm, so calls
pair by (client, ordinal).
"""
import os
import sys
from dataclasses import replace

import fuzz
import rtc
from runner import run_jobs
from sim import LATE_BINS, simulate

HERE = os.path.dirname(os.path.abspath(__file__))


def _by_client(sim):
    out, seen = {}, {}
    for c in sim.calls:
        if c.cid < 0:
            continue
        k = seen.get(c.cid, 0)
        seen[c.cid] = k + 1
        out[(c.cid, k)] = c
    return out


def pair_calls(a, b):
    """[(call in a, same call in b)] for calls issued in both runs."""
    xa, xb = _by_client(a), _by_client(b)
    return [(xa[k], xb[k]) for k in xa if k in xb]


def fate(old, new):
    """What run to completion makes of each paired old-rule timeout."""
    counts = {"ok_on_time": 0, "ok_late": 0, "run_limit": 0, "refused": 0}
    late, n, late_from_ok = [], 0, 0
    for x, y in pair_calls(old, new):
        if y.outcome == "ok" and y.t_res > y.deadline and x.outcome == "ok":
            late_from_ok += 1
        if x.outcome != "timeout" or y.outcome is None:
            continue
        n += 1
        if y.outcome == "ok":
            lat = y.t_res - y.t_arr
            if y.t_res > y.deadline:
                counts["ok_late"] += 1
                late.append(lat)
            else:
                counts["ok_on_time"] += 1
        elif y.outcome == "timeout":
            counts["run_limit"] += 1
        else:
            counts["refused"] += 1
    hist = [sum(1 for v in late if lo < v <= (hi if hi != "inf" else float("inf"))) for lo, hi in LATE_BINS]
    return {"paired_timeouts": n, "counts": counts, "late_latency": late, "late_hist": hist,
            "late_from_ok": late_from_ok}


def job(arg):
    cfg, tag = arg
    old = simulate(replace(cfg, admission="fifo_shed", threshold=rtc.CHECKS["p90"][1], run_limit=None), fuzz.SVC)
    row = dict(tag)
    for rl in (30.0, 60.0):
        new = simulate(replace(cfg, admission="fifo", run_limit=rl), fuzz.SVC)
        fr = fate(old, new)
        p = f"rl{int(rl)}_"
        row[p + "timeouts"] = fr["paired_timeouts"]
        row.update({p + k: v for k, v in fr["counts"].items()})
        row.update({f"{p}h_{lo}_{hi}": v for (lo, hi), v in zip(LATE_BINS, fr["late_hist"])})
        row[p + "late_from_ok"] = fr["late_from_ok"]
    return row


def jobs(n_real=500):
    for band, i, base in rtc.bands(n_real, 0):
        base = replace(base, queue_limit=32, dispatch="P2")
        for tail in ("base", "long"):
            yield (base if tail == "base" else rtc.long_tail(base)), {"band": band, "cfg_i": i, "tail": tail}


def summary(rows):
    out = ["# Fate of the old rule's timeouts under run to completion (generated by rtc_pairing.py)", "",
           "Realistic band, P2, queue 32; old rule = p90 start check with the deadline ending running calls; new = "
           "wait-only start check. Calls paired by (client, ordinal) under common random numbers.", ""]
    keys = ["ok_on_time", "ok_late", "run_limit", "refused"]
    out.append("| tail | run limit | old timeouts paired | answered on time | answered late | hit run limit | "
               "refused | late answers that were on time under the old rule |")
    out.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    hist_rows = []
    for tail in ("base", "long"):
        for rl in (30, 60):
            p = f"rl{rl}_"
            rs = [r for r in rows if r["tail"] == tail]
            n = sum(r[p + "timeouts"] for r in rs)
            c = {k: sum(r[p + k] for r in rs) for k in keys}
            lfo = sum(r[p + "late_from_ok"] for r in rs)
            out.append(f"| {tail} | {rl} s | {n} | " + " | ".join(f"{c[k]} ({100 * c[k] / max(1, n):.1f} %)"
                                                              for k in keys) + f" | {lfo} |")
            h = [sum(r[f"{p}h_{lo}_{hi}"] for r in rs) for lo, hi in LATE_BINS]
            hist_rows.append(f"| {tail} | {rl} s | " + " | ".join(f"{v} ({100 * v / max(1, sum(h)):.0f} %)"
                                                                 for v in h) + " |")
    out += ["", "Latency of the former timeouts that now answer late:", "",
            "| tail | run limit | (10,12] s | (12,15] | (15,20] | (20,30] | (30,60] | (60,120] | > 120 |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"] + hist_rows + [""]
    return "\n".join(out)


if __name__ == "__main__":
    n_real = int(sys.argv[1]) if len(sys.argv) > 1 else 500
    rows, n_err = run_jobs("rtc pairing", job, jobs(n_real), os.path.join(HERE, "results", "rtc_pairing"),
                           os.path.join(HERE, "results", "rtc.log"), every=200)
    open(os.path.join(HERE, "results", "rtc_pairing.md"), "w").write(summary(rows))
    print(summary(rows))
    sys.exit(1 if n_err else 0)
