def test_toolchain_and_format_checks(tool: ModuleType) -> None:
    def missing(command: list[str], cwd: Path, env: Any = None) -> str:
        raise tool.HiddenSurfaceError(f"command failed: {' '.join(command)}")

    with mock.patch.object(tool, "_run", missing):
        expect_error(tool, tool.check_toolchain, tool.PINNED_NIGHTLY)

    good = doc("facade-default")
    assert good["format_version"] == tool.FORMAT_VERSION == 57
    bad = copy.deepcopy(good)
    bad["format_version"] = 56
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "hs_facade.json"
        path.write_text(json.dumps(bad))
        expect_error(tool, lambda: tool.load_rustdoc(path), "format_version")
        path.write_text(json.dumps(good))
        assert tool.load_rustdoc(path)["format_version"] == 57

        # A capture failure writes no output.
        output = Path(directory) / "never.json"
        with (
            mock.patch.object(tool, "validate_source_sha", lambda sha: sha),
            mock.patch.object(
                tool,
                "capture_source_sha",
                mock.Mock(side_effect=tool.HiddenSurfaceError("format_version 56")),
            ),
            mock.patch("sys.stderr"),
        ):
            assert (
                tool.main(["capture", "--source-sha", SHA, "--output", str(output)])
                == 2
            )
        assert not output.exists()


