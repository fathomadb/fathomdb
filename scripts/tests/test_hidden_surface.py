def test_source_sha_validation(tool: ModuleType) -> None:
    head = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
    ).stdout.strip()
    tree = subprocess.run(
        ["git", "rev-parse", "HEAD^{tree}"],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
    ).stdout.strip()
    assert tool.validate_source_sha(head) == head
    expect_error(tool, lambda: tool.validate_source_sha(head[:12]), "40")
    expect_error(tool, lambda: tool.validate_source_sha(head.upper()), "40")
    expect_error(tool, lambda: tool.validate_source_sha("0" * 40), "commit")
    expect_error(tool, lambda: tool.validate_source_sha(tree), "commit")

    # A bad SHA fails before any toolchain, export, or build command runs.
    calls: list[list[str]] = []
    real_run = tool._run

    def recording_run(command: list[str], cwd: Path, env: Any = None) -> str:
        calls.append(list(command))
        if command[0] != "git":
            raise AssertionError(f"non-git command before validation: {command}")
        return real_run(command, cwd, env)

    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "out.json"
        for bad in (head[:12], "0" * 40, tree):
            with (
                mock.patch.object(tool, "_run", recording_run),
                mock.patch("sys.stderr"),
            ):
                assert (
                    tool.main(["capture", "--source-sha", bad, "--output", str(output)])
                    == 2
                )
        assert not output.exists()
    assert all(command[:2] == ["git", "cat-file"] for command in calls), calls


