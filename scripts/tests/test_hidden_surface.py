        recorded = (JSON / f"probe-{crate}.jsonl").read_text()
        statuses = tool.probe_statuses(recorded, ranges)
        assert statuses == [item.expected for item in items], (crate, statuses)
        entries = tool.probe_row_entries(items, statuses)
        assert [(e["path"], e["kind"], e["signature"]) for e in entries] == [
            (item.path, "release-probe", item.expected) for item in items
        ]
        flipped = ["resolved" if s == "unresolved" else "unresolved" for s in statuses]
        expect_error(
            tool,
            lambda items=items, flipped=flipped: tool.probe_row_entries(items, flipped),
            "release probe",
        )

