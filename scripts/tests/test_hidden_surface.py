TOOL = ROOT / "dev" / "tools" / "hidden_surface.py"
FIXTURES = ROOT / "scripts" / "tests" / "fixtures" / "hidden-surface"
JSON = FIXTURES / "json"
SHA = "1" * 40
OTHER_SHA = "2" * 40


def load_tool() -> ModuleType:
    spec = importlib.util.spec_from_file_location("hidden_surface", TOOL)
    if spec is None or spec.loader is None:
        raise AssertionError(f"cannot load hidden-surface tool: {TOOL}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def doc(name: str) -> dict[str, Any]:
    return json.loads((JSON / f"{name}.json").read_text())


def by_path(records: list[Any]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for record in records:
        assert record.path not in result, f"duplicate path {record.path}"
        result[record.path] = record
    return result


def sig(record: Any) -> dict[str, Any]:
    return json.loads(record.signature)


def entry_keys(entries: list[dict[str, str]]) -> set[tuple[str, str, str]]:
    return {(e["path"], e["kind"], e["signature"]) for e in entries}


def expect_error(tool: ModuleType, call: Callable[[], Any], fragment: str) -> None:
    try:
        call()
    except tool.HiddenSurfaceError as exc:
        assert fragment in str(exc), (fragment, str(exc))
        return
    raise AssertionError(f"expected HiddenSurfaceError containing {fragment!r}")


OFFSET = 100_000
ID_LIST_KEYS = {"items", "impls", "variants", "fields", "implementations", "tuple"}


def renumber(value: Any, key: str | None = None) -> Any:
    """Consistently shift every rustdoc id, including map keys and id lists."""

    if isinstance(value, dict):
        shifted: dict[str, Any] = {}
        for child_key, child in value.items():
            if child_key in ("id", "root") and isinstance(child, int):
                shifted[child_key] = child + OFFSET
            elif child_key == "links" and isinstance(child, dict):
                shifted[child_key] = {k: v + OFFSET for k, v in child.items()}
            else:
                shifted[child_key] = renumber(child, child_key)
        return shifted
    if isinstance(value, list):
        if key in ID_LIST_KEYS and all(
            isinstance(item, int) or item is None for item in value
        ):
            return [item + OFFSET if isinstance(item, int) else item for item in value]
        return [renumber(item, key) for item in value]
    return value


def renumbered(document: dict[str, Any]) -> dict[str, Any]:
    result = renumber(document)
    result["index"] = {str(int(k) + OFFSET): v for k, v in result["index"].items()}
    result["paths"] = {str(int(k) + OFFSET): v for k, v in result["paths"].items()}
    return result


def manifest(
    tool: ModuleType, rows: dict[str, list[dict[str, str]]], **extra: Any
) -> dict[str, Any]:
    metadata = {
        "schema": tool.SCHEMA,
        "capture_source_sha": SHA,
        "source_modified": False,
        "tools": {
            "rust-toolchain": tool.PINNED_NIGHTLY,
            "rustc": "rustc 1.97.0-nightly",
        },
        "rustdoc_format_version": tool.FORMAT_VERSION,
        "target": "x86_64-unknown-linux-gnu",
        "row_identities": [{"id": row_id} for row_id in sorted(rows)],
    }
    metadata.update(extra)
    return tool.build_manifest(metadata, rows)


def test_cfg_parser(tool: ModuleType) -> None:
    span = "src/lib.rs:1:7: 1:23 (#0)"
    parse = tool.parse_cfg_attr
    assert (
        parse(
            f'#[attr = CfgTrace([NameValue {{ name: "debug_assertions", value: None, span: {span} }}])]'
        )
        == "debug_assertions"
    )
    assert (
        parse(
            f'#[attr = CfgTrace([NameValue {{ name: "feature", value: Some("hooks"), span: {span} }}])]'
        )
        == 'feature = "hooks"'
    )
    assert (
        parse(
            f'#[attr = CfgTrace([Not(NameValue {{ name: "feature", value: Some("hooks"), span: {span} }}, {span})])]'
        )
        == 'not(feature = "hooks")'
    )
    # any/all operands are sorted into canonical order.
    assert (
        parse(
            "#[attr = CfgTrace([Any(["
            f'NameValue {{ name: "test", value: None, span: {span} }}, '
            f'NameValue {{ name: "debug_assertions", value: None, span: {span} }}, '
            f'NameValue {{ name: "feature", value: Some("test-hooks"), span: {span} }}'
            f"], {span})])]"
        )
        == 'any(debug_assertions, feature = "test-hooks", test)'
    )
    assert (
        parse(
            "#[attr = CfgTrace([All(["
            f'NameValue {{ name: "debug_assertions", value: None, span: {span} }}, '
            f'Not(NameValue {{ name: "feature", value: Some("hooks"), span: {span} }}, {span})'
            f"], {span})])]"
        )
        == 'all(debug_assertions, not(feature = "hooks"))'
    )
    # Two stacked predicates in one trace are a conjunction.
    assert (
        parse(
            "#[attr = CfgTrace(["
            f'NameValue {{ name: "test", value: None, span: {span} }}, '
            f'NameValue {{ name: "debug_assertions", value: None, span: {span} }}'
            "])]"
        )
        == "all(debug_assertions, test)"
    )
    for bad in (
        "#[attr = CfgTrace([Bool { value: true }])]",
        '#[attr = CfgTrace([NameValue { name: "x", value: None }])]',
        f'#[attr = CfgTrace([NameValue {{ name: "x", value: None, span: {span} }}]) trailing]',
        "#[cfg(debug_assertions)]",
    ):
        expect_error(tool, lambda bad=bad: parse(bad), "cfg")


def test_walk_hazards(tool: ModuleType) -> None:
    records = by_path(tool.walk(doc("base-default")))
    root = "hs_fixture"

    def p(name: str) -> Any:
        full = f"{root}::{name}"
        assert full in records, (full, sorted(records))
        return records[full]

    assert records[root].kind == "module"
    # Doc-hidden items at each site.
    assert sig(p("hidden_fn_for_test"))["own_hidden"] is True
    assert sig(p("hidden_mod"))["own_hidden"] is True
    assert p("hidden_mod::inside").kind == "function"
    plain = sig(p("plain_target"))
    assert plain["use_hidden"] is True and plain["own_hidden"] is False
    hidden_impl = sig(p("Thing::hidden_impl_method"))
    assert hidden_impl["impl_hidden"] is True and hidden_impl["own_hidden"] is False
    assert sig(p("Thing::peek_for_test"))["own_hidden"] is True
    assert sig(p("Thing::hidden_field"))["own_hidden"] is True
    assert sig(p("hook_for_test"))["own_hidden"] is True
    # Named and aliased re-exports carry the target's signature.
    assert p("make").kind == "function"
    assert sig(p("make"))["inner"] == sig(p("make_alias"))["inner"]
    assert '"path":"hs_fixture::Thing"' in p("make").signature
    # Glob expansion, with explicit items shadowing glob names.
    assert p("g1").kind == "function" and p("G2").kind == "struct"
    assert '"primitive":"u8"' in p("shadowed").signature
    assert '"primitive":"u16"' not in p("shadowed").signature
    external_glob = p("ext_glob::external-glob:core::hint")
    assert external_glob.kind == "external-glob"
    assert json.loads(external_glob.signature) == {
        "source": "core::hint",
        "use_cfg": None,
        "use_hidden": False,
    }
    # A cyclic module re-export is recorded once and not expanded.
    assert p("cyc::again").kind == "module"
    assert f"{root}::cyc::again::in_cyc" not in records
    assert p("vm_alias::vis").kind == "function"
    # Enum variants, struct fields, trait items.
    for variant in ("Unit", "Pair", "Named"):
        assert p(f"Shape::{variant}").kind == "variant"
    assert '"path":"hs_fixture::Thing"' in p("Shape::Pair").signature
    assert sig(p("Shape"))["inner"]["enum"]["variants"] == ["Named", "Pair", "Unit"]
    for item, kind in (
        ("LIMIT", "assoc_const"),
        ("Out", "assoc_type"),
        ("go", "function"),
        ("provided", "function"),
    ):
        assert p(f"Probe::{item}").kind == kind
    assert p("Tuple::0").kind == "struct_field" and p("Tuple::1").kind == "struct_field"
    assert f"{root}::Tuple::2" not in records
    assert f"{root}::Thing::y" not in records
    # Inherent impl items and trait impls with rendered generic arguments.
    assert p("Thing::get").kind == "function"
    for trait in (
        "core::clone::Clone",
        "core::convert::From<u32>",
        "core::convert::From<hs_fixture::Shape>",
        "hs_fixture::Probe",
    ):
        assert p(f"Thing::impl {trait}").kind == "impl"
    # Synthetic auto-trait impls and blanket instantiations are skipped.
    assert not any("impl core::marker::Send" in path for path in records)
    assert not any("impl core::convert::Into" in path for path in records)
    # The local blanket impl.
    assert p("impl hs_fixture::Marker for T").kind == "impl"
    # A constant whose expression names another constant keeps no `expr`.
    derived = p("DERIVED").signature
    assert "expr" not in derived and '"value"' in derived
    # Unreachable types are named by kind and name, with collision suffixes.
    tokens = p("takes_tokens").signature
    assert "private:struct:Token#1" in tokens and "private:struct:Token#2" in tokens
    assert "sealed" not in tokens
    # No rustdoc id or source location survives normalization.
    for record in records.values():
        assert '"id"' not in record.signature and '"span"' not in record.signature
        assert "src/" not in record.signature, record.path


def test_cfg_sites(tool: ModuleType) -> None:
    default = by_path(tool.walk(doc("base-default")))
    hooks = by_path(tool.walk(doc("base-hooks")))
    root = "hs_fixture::"
    assert sig(default[root + "debug_only_for_test"])["own_cfg"] == "debug_assertions"
    assert sig(default[root + "without_hooks"])["own_cfg"] == 'not(feature = "hooks")'
    assert (
        sig(default[root + "any_gate"])["own_cfg"]
        == 'any(debug_assertions, feature = "hooks", test)'
    )
    assert (
        sig(default[root + "all_gate"])["own_cfg"]
        == 'all(debug_assertions, not(feature = "hooks"))'
    )
    reexported = sig(default[root + "debug_reexported"])
    assert reexported["use_cfg"] == "debug_assertions" and reexported["own_cfg"] is None
    assert (
        sig(default[root + "Thing::debug_impl_method"])["impl_cfg"]
        == "debug_assertions"
    )
    assert sig(default[root + "Thing::impl hs_fixture::DebugOnlyTrait"])[
        "impl_cfg"
    ] == ("debug_assertions")
    assert sig(default[root + "Thing::debug_field"])["own_cfg"] == "debug_assertions"
    # Feature-gated hooks exist only in the feature row.
    assert root + "gated_hook" not in default
    assert sig(hooks[root + "gated_hook"])["own_cfg"] == 'feature = "hooks"'
    assert root + "reexport_gated_target" not in default
    assert sig(hooks[root + "reexport_gated_target"])["use_cfg"] == 'feature = "hooks"'
    assert root + "without_hooks" not in hooks and root + "all_gate" not in hooks
    # Release-only items are invisible to rustdoc.
    assert root + "release_only_proof" not in default
    # Predicates are the conjunction of every site plus ancestors.
    assert default[root + "Thing::debug_impl_method"].preds == ("debug_assertions",)
    assert default[root + "Thing::get"].preds == ()

    broken = doc("base-default")
    for item in broken["index"].values():
        if item["name"] == "debug_only_for_test":
            item["attrs"] = [{"other": "#[attr = CfgTrace([Unknown(1)])]"}]
    expect_error(tool, lambda: tool.walk(broken), "cfg")


