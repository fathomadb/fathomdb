/// Hard cap on the number of nodes returned by a single `graph_neighbors` call.
/// Ported from v0.5.6 `MAX_TRAVERSAL_DEPTH` (applied as a LIMIT on the CTE and
/// the final SELECT). Defense-in-depth against unbounded traversal.
const GRAPH_NEIGHBORS_HARD_CAP: usize = 50;

/// Build the BFS CTE SQL for the given `direction`, under `view`.
///
/// Parameters (positional):
///   `?1` — root `logical_id`
///   `?2` — max_depth (`u32`, SDK-facing depth ceiling ≤ 3)
///   `?3` — R-20-NV node-validity instant (`:now` seam), emitted at EVERY node
///          position; omitted entirely when the view relaxes validity.
///
/// `LIMIT {GRAPH_NEIGHBORS_HARD_CAP}` appears on both the CTE and the final SELECT.
///
/// # Why one template instead of three
///
/// The three directions previously carried three hand-maintained copies of the
/// CTE, each repeating the node predicate at THREE positions (anchor, recursive
/// join, final projection) — nine hand-written copies in total. R-20-RV requires
/// a relax flag to apply at every one of them, and nine copies is exactly the
/// shape in which "it works on `Outgoing` but silently not on `Both`" hides. The
/// directions are folded into ONE template parameterised by the two things that
/// actually differ (the edge join condition and the traversed-to expression), so
/// `view.node_sql(...)` is written once per position and applying to all three
/// directions is structural rather than a thing to remember.
///
/// **TC-33: the `canonical_edges` temporal filter is now parameterised too.** It
/// was `datetime(e.t_invalid) > datetime('now')` inline, deliberately left alone
/// while edge validity was ISO-8601 TEXT. Edge timestamps are INTEGER epoch
/// seconds now, so the predicate is generated by [`edge_validity_sql`] and binds
/// the frozen instant at `?4` — no inline clock remains in this template.
fn build_bfs_sql(
    direction: TraversalDirection,
    view: &ReadView,
    scope: &ScopePredicate,
    binds: &mut Vec<rusqlite::types::Value>,
) -> String {
    let cap = GRAPH_NEIGHBORS_HARD_CAP;
    let cte_cap = cap * cap;

    const NOW_IDX: usize = 3;
    const EDGE_NOW_IDX: usize = 4;

    let (edge_join, target_expr) = match direction {
        TraversalDirection::Outgoing => ("e.from_id = t.logical_id", "e.to_id"),
        TraversalDirection::Incoming => ("e.to_id = t.logical_id", "e.from_id"),
        TraversalDirection::Both => (
            "(e.from_id = t.logical_id OR e.to_id = t.logical_id)",
            "CASE WHEN e.from_id = t.logical_id THEN e.to_id ELSE e.from_id END",
        ),
    };

    let anchor_node = view.node_sql("n", NOW_IDX);
    let next_node = view.node_sql("next_n", NOW_IDX);
    let projection_node = view.node_sql("n", NOW_IDX);
    let edge_valid = edge_validity_sql_for_view("e", EDGE_NOW_IDX, view);
    let mut anchor_scope_sql = String::new();
    scope.append_sql_values("n.scope", &mut anchor_scope_sql, binds);

    format!(
        "WITH RECURSIVE
  traversal(scope, logical_id, depth, visited) AS (
    SELECT n.scope, n.logical_id, 0, char(30) || hex(n.scope) || char(31) || n.logical_id || char(30)
    FROM canonical_nodes n
    WHERE n.logical_id = ?1 AND ({anchor_scope_sql}){anchor_node}
    UNION ALL
    SELECT t.scope, {target_expr}, t.depth + 1, t.visited || hex(t.scope) || char(31) || {target_expr} || char(30)
    FROM traversal t
    JOIN canonical_edges e ON e.scope = t.scope AND {edge_join}
    JOIN canonical_nodes next_n ON next_n.scope = e.scope AND next_n.logical_id = {target_expr}{next_node}
    WHERE t.depth < ?2
      AND e.superseded_at IS NULL{edge_valid}
      AND instr(t.visited, char(30) || hex(t.scope) || char(31) || {target_expr} || char(30)) = 0
    LIMIT {cte_cap}
  )
SELECT DISTINCT n.logical_id, n.kind, n.body, n.write_cursor, n.properties
FROM traversal tr
JOIN canonical_nodes n ON n.scope = tr.scope AND n.logical_id = tr.logical_id
WHERE tr.logical_id != ?1{projection_node}
LIMIT {cap}"
    )
}

/// Build the BFS CTE SQL for `search_expand` — identical to `build_bfs_sql`
/// but the final SELECT uses `GROUP BY` + `MIN(tr.depth)` so that each
/// expanded node carries its actual BFS distance from the root.
///
/// Returns 7 columns: logical_id, kind, body, write_cursor, min_depth, properties, scope.
fn build_bfs_with_depth_sql(
    connection: &Connection,
    view: FrozenView,
    filter: Option<&SearchFilter>,
) -> rusqlite::Result<(String, Vec<rusqlite::types::Value>)> {
    let cap = GRAPH_NEIGHBORS_HARD_CAP;
    let cte_cap = cap * cap;
    let anchor_node = view.node_sql("n", 3);
    let next_node = view.node_sql("next_n", 3);
    let projection_node = view.node_sql("n", 3);
    let edge_valid = edge_validity_sql_for_view("e", 3, &view.view);
    let edge_existence = view.view.edge_existence_sql("e");
    let mut params = vec![rusqlite::types::Value::Null; 4];
    let anchor_eligibility = crate::filter::append_node_eligibility_sql_view(
        connection,
        filter,
        "n",
        &mut params,
        &view.view,
    )?;
    let next_eligibility = crate::filter::append_node_eligibility_sql_view(
        connection,
        filter,
        "next_n",
        &mut params,
        &view.view,
    )?;
    let projection_eligibility = crate::filter::append_node_eligibility_sql_view(
        connection,
        filter,
        "n",
        &mut params,
        &view.view,
    )?;
    let sql=format!("WITH RECURSIVE traversal(scope,logical_id,depth,visited) AS (
      SELECT DISTINCT n.scope,n.logical_id,0,char(30)||hex(n.scope)||char(31)||n.logical_id||char(30)
      FROM canonical_nodes n WHERE n.scope=?4 AND n.logical_id=?1 AND ?3 IS NOT NULL{anchor_node}{anchor_eligibility}
      UNION ALL
      SELECT t.scope,CASE WHEN e.from_id=t.logical_id THEN e.to_id ELSE e.from_id END,t.depth+1,
        t.visited || hex(t.scope) || char(31) || CASE WHEN e.from_id=t.logical_id THEN e.to_id ELSE e.from_id END || char(30)
      FROM traversal t JOIN canonical_edges e ON e.scope=t.scope AND (e.from_id=t.logical_id OR e.to_id=t.logical_id)
      WHERE t.depth<?2{edge_existence}{edge_valid}
        AND EXISTS(SELECT 1 FROM canonical_nodes next_n
          WHERE next_n.scope=e.scope AND next_n.logical_id=CASE WHEN e.from_id=t.logical_id THEN e.to_id ELSE e.from_id END
          {next_node}{next_eligibility})
        AND instr(t.visited,char(30)||hex(t.scope)||char(31)||CASE WHEN e.from_id=t.logical_id THEN e.to_id ELSE e.from_id END||char(30))=0
      LIMIT {cte_cap}
    ), reached AS (SELECT scope,logical_id,MIN(depth) AS min_depth FROM traversal GROUP BY scope,logical_id),
    candidates AS (
      SELECT n.logical_id,n.kind,n.body,n.write_cursor,r.min_depth,n.properties,n.scope,
        ROW_NUMBER() OVER(PARTITION BY n.scope,n.logical_id ORDER BY n.write_cursor DESC) AS revision_rank
      FROM reached r JOIN canonical_nodes n ON n.scope=r.scope AND n.logical_id=r.logical_id
      WHERE r.logical_id!=?1{projection_node}{projection_eligibility}
    ) SELECT logical_id,kind,body,write_cursor,min_depth,properties,scope FROM candidates WHERE revision_rank=1
      ORDER BY min_depth,logical_id,scope LIMIT {cap}");
    Ok((sql, params))
}

/// 0.8.20 Slice 10b (R-20-NV) — the validity-boundary hook, on the DEFERRED
/// reader transaction.
///
/// Reports nodes whose `valid_from` and/or `valid_until` falls in the half-open
/// interval `(since, upper]`. Both bounds are BOUND parameters (`?1`, `?2`) —
/// the node-validity path never inlines `datetime('now')`.
///
/// The view's EXISTENCE conjunct applies (default: current + active rows only);
/// its VALIDITY conjunct deliberately does not, because the question is "did
/// this window cross a boundary", not "is this row valid now".
pub(crate) fn crossed_boundary_since_in_tx(
    reader: &mut Connection,
    since: i64,
    view: &ReadView,
    scope: &crate::scope::ScopePredicate,
    attribution: &Arc<WalAttributionCollector>,
    worker_idx: usize,
) -> rusqlite::Result<Vec<BoundaryCrossing>> {
    // `now_param()` is None exactly when the view relaxes validity, which here
    // means "no upper bound on the interval".
    let upper = view.now_param().unwrap_or(i64::MAX);
    let mut binds =
        vec![rusqlite::types::Value::Integer(since), rusqlite::types::Value::Integer(upper)];
    let mut scope_sql = String::new();
    scope.append_sql_values("canonical_nodes.scope", &mut scope_sql, &mut binds);
    let existence = view.existence_sql("canonical_nodes");
    let eligibility = dependency_closure::read_eligibility_sql(
        "canonical_nodes",
        view.include_superseded,
        view.include_inactive,
        view.include_out_of_window,
        2,
    );
    let sql = format!(
        "SELECT logical_id, kind, body, write_cursor, valid_from, valid_until, properties \
         FROM canonical_nodes \
         WHERE {scope_sql}{existence}{eligibility} \
           AND logical_id IS NOT NULL \
           AND ( (valid_from IS NOT NULL AND valid_from > ?1 AND valid_from <= ?2) \
              OR (valid_until IS NOT NULL AND valid_until > ?1 AND valid_until <= ?2) ) \
         ORDER BY write_cursor"
    );
    let tx = begin_attributed_reader_tx(reader, attribution, worker_idx)?;
    let mut statement = tx.prepare(&sql)?;
    let rows = statement.query_map(rusqlite::params_from_iter(binds.iter()), |row| {
        let valid_from: Option<i64> = row.get(4)?;
        let valid_until: Option<i64> = row.get(5)?;
        Ok(BoundaryCrossing {
            node: NodeRecord {
                logical_id: row.get(0)?,
                kind: row.get(1)?,
                body: row.get(2)?,
                write_cursor: row.get::<_, i64>(3)? as u64,
                properties: crate::properties::decode_properties_row_col(row, 6)?,
            },
            became_valid_at: valid_from.filter(|t| *t > since && *t <= upper),
            became_invalid_at: valid_until.filter(|t| *t > since && *t <= upper),
        })
    })?;
    let mut out = Vec::new();
    for row in rows {
        out.push(row?);
    }
    Ok(out)
}

/// Slice 20 (G5) — execute a bounded BFS on the DEFERRED reader transaction.
/// Called inside the reader worker loop.
#[allow(clippy::too_many_arguments)]
pub(crate) fn graph_neighbors_in_tx(
    reader: &mut Connection,
    root_logical_id: &str,
    depth: u32,
    direction: TraversalDirection,
    view: &ReadView,
    scope: &ScopePredicate,
    attribution: &Arc<WalAttributionCollector>,
    worker_idx: usize,
) -> rusqlite::Result<Vec<NodeRecord>> {
    #[cfg(feature = "tc5-benchmark")]
    tc5_benchmark::record_graph_route();
    let depth_i64 = depth as i64;
    let frozen = (*view).freeze();
    let mut binds: Vec<rusqlite::types::Value> = vec![
        rusqlite::types::Value::Text(root_logical_id.to_string()),
        rusqlite::types::Value::Integer(depth_i64),
        rusqlite::types::Value::Integer(frozen.now_param().unwrap_or_default()),
        rusqlite::types::Value::Integer(frozen.edge_now()),
    ];
    let sql = build_bfs_sql(direction, view, scope, &mut binds);
    let tx = begin_attributed_reader_tx(reader, attribution, worker_idx)?;
    let mut statement = tx.prepare(&sql)?;
    let rows = statement.query_map(rusqlite::params_from_iter(binds.iter()), |row| {
        Ok(NodeRecord {
            logical_id: row.get(0)?,
            kind: row.get(1)?,
            body: row.get(2)?,
            write_cursor: row.get::<_, i64>(3)? as u64,
            properties: crate::properties::decode_properties_row_col(row, 4)?,
        })
    })?;
    let mut out = Vec::new();
    for row in rows {
        out.push(row?);
    }
    Ok(out)
}

/// Slice 20 (G6) — resolve search hit `write_cursor`s to `logical_id`s, run
/// BFS for each root, and merge into a [`SearchExpandResult`]. Called inside
/// the reader worker loop on the DEFERRED reader transaction.
#[allow(clippy::too_many_arguments)]
pub(crate) fn search_expand_in_tx(
    reader: &mut Connection,
    search_hits: &[SearchHit],
    depth: u32,
    view: ReadView,
    filter: Option<&SearchFilter>,
    scope: &ScopePredicate,
    frozen_binding: Option<&frozen_read::FrozenReadBinding>,
    attribution: &Arc<WalAttributionCollector>,
    worker_idx: usize,
) -> Result<SearchExpandResult, SearchExpandHandlerError> {
    let tx = begin_attributed_reader_tx(reader, attribution, worker_idx)?;
    if let Some(expected) = frozen_binding {
        frozen_read::validate_snapshot(&tx, expected)
            .map_err(SearchExpandHandlerError::FrozenRead)?;
    }
    if let Some(filter) = filter {
        validate_filter_attributes_on_snapshot(&tx, filter)?;
    }
    let result = search_expand_on_snapshot(&tx, search_hits, depth, view.freeze(), filter, scope)?;
    tx.commit()?;
    Ok(result)
}

/// Resolve and expand search hits on an already-pinned reader snapshot.
pub(crate) fn search_expand_on_snapshot<H: RankedHit>(
    tx: &Connection,
    search_hits: &[H],
    depth: u32,
    frozen: FrozenView,
    filter: Option<&SearchFilter>,
    scope: &ScopePredicate,
) -> Result<SearchExpandResult, SearchExpandHandlerError> {
    let mut hit_logical_ids: Vec<Option<(String, String)>> = Vec::with_capacity(search_hits.len());
    {
        let node_predicate = frozen.node_sql("canonical_nodes", 2);
        let mut node_prefix_params = vec![rusqlite::types::Value::Integer(0)];
        if let Some(now) = frozen.now_param() {
            node_prefix_params.push(rusqlite::types::Value::Integer(now));
        }
        let mut node_scope_sql = String::new();
        scope.append_sql_values(
            "canonical_nodes.scope",
            &mut node_scope_sql,
            &mut node_prefix_params,
        );
        let mut node_stmt = tx.prepare(&format!(
            "SELECT logical_id, scope FROM canonical_nodes
             WHERE write_cursor = ?1 AND ({node_scope_sql}){node_predicate}
             LIMIT 1"
        ))?;
        let edge_existence = frozen.view.edge_existence_sql("canonical_edges");
        let edge_predicate = edge_validity_sql_for_view("canonical_edges", 2, &frozen.view);
        let mut edge_prefix_params = vec![
            rusqlite::types::Value::Integer(0),
            rusqlite::types::Value::Integer(frozen.edge_now()),
        ];
        let mut edge_scope_sql = String::new();
        scope.append_sql_values(
            "canonical_edges.scope",
            &mut edge_scope_sql,
            &mut edge_prefix_params,
        );
        let mut edge_stmt = tx.prepare(&format!(
            "SELECT 1 FROM canonical_edges
             WHERE write_cursor = ?1 AND ({edge_scope_sql}){edge_existence}{edge_predicate}
             LIMIT 1"
        ))?;
        for hit in search_hits {
            let hit = hit.hit();
            if hit.branch == SoftFallbackBranch::TextEdge {
                let cursor_i64 = hit.write_cursor as i64;
                edge_prefix_params[0] = rusqlite::types::Value::Integer(cursor_i64);
                let active: Option<i32> = edge_stmt
                    .query_row(rusqlite::params_from_iter(edge_prefix_params.iter()), |row| {
                        row.get(0)
                    })
                    .optional()?;
                if active.is_some() {
                    hit_logical_ids.push(Some((String::new(), String::new())));
                } else {
                    hit_logical_ids.push(None);
                }
            } else {
                let cursor_i64 = hit.write_cursor as i64;
                node_prefix_params[0] = rusqlite::types::Value::Integer(cursor_i64);
                let resolved = node_stmt
                    .query_row(rusqlite::params_from_iter(node_prefix_params.iter()), |row| {
                        Ok((row.get::<_, Option<String>>(0)?, row.get::<_, String>(1)?))
                    })
                    .optional()?;
                match resolved {
                    None => hit_logical_ids.push(None),
                    Some((None, _)) => hit_logical_ids.push(Some((String::new(), String::new()))),
                    Some((Some(lid), row_scope)) => hit_logical_ids.push(Some((row_scope, lid))),
                }
            }
        }
    }

    let hit_id_set: std::collections::HashSet<(String, String)> =
        hit_logical_ids.iter().flatten().filter(|(_, lid)| !lid.is_empty()).cloned().collect();

    let (bfs_sql, bfs_parameter_template) = build_bfs_with_depth_sql(tx, frozen, filter)?;
    let depth_i64 = depth as i64;
    let mut nearest_hop: std::collections::HashMap<(String, String), (NodeRecord, u32)> =
        std::collections::HashMap::new();

    if depth > 0 {
        let mut bfs_stmt = tx.prepare(&bfs_sql)?;
        let edge_now = frozen.edge_now();
        for (root_scope, root_id) in
            hit_logical_ids.iter().flatten().filter(|(_, lid)| !lid.is_empty())
        {
            let mut binds = bfs_parameter_template.clone();
            binds[0] = rusqlite::types::Value::Text(root_id.clone());
            binds[1] = rusqlite::types::Value::Integer(depth_i64);
            binds[2] = rusqlite::types::Value::Integer(edge_now);
            binds[3] = rusqlite::types::Value::Text(root_scope.clone());
            let neighbor_rows =
                bfs_stmt.query_map(rusqlite::params_from_iter(binds.iter()), |row| {
                    let node = NodeRecord {
                        logical_id: row.get(0)?,
                        kind: row.get(1)?,
                        body: row.get(2)?,
                        write_cursor: row.get::<_, i64>(3)? as u64,
                        properties: crate::properties::decode_properties_row_col(row, 5)?,
                    };
                    let min_depth: i64 = row.get(4)?;
                    let row_scope: String = row.get(6)?;
                    Ok((row_scope, node, min_depth as u32))
                })?;
            for row_result in neighbor_rows {
                let (row_scope, node, hop_count) = row_result?;
                let key = (row_scope, node.logical_id.clone());
                if hit_id_set.contains(&key) {
                    continue;
                }
                nearest_hop
                    .entry(key)
                    .and_modify(|(_, prev_hop)| {
                        if hop_count < *prev_hop {
                            *prev_hop = hop_count;
                        }
                    })
                    .or_insert((node, hop_count));
            }
        }
    }

    let mut expanded: Vec<(NodeRecord, u32)> = nearest_hop.into_values().collect();
    expanded.sort_by(|(a, _), (b, _)| {
        a.logical_id.cmp(&b.logical_id).then_with(|| a.write_cursor.cmp(&b.write_cursor))
    });

    let resolved_hits: Vec<SearchHit> = search_hits
        .iter()
        .zip(hit_logical_ids.iter())
        .filter_map(|(hit, lid)| lid.as_ref().map(|_| hit.hit().clone()))
        .collect();

    let mut all_logical_ids: Vec<String> = hit_logical_ids
        .into_iter()
        .flatten()
        .filter_map(|(_, lid)| (!lid.is_empty()).then_some(lid))
        .collect();
    for (node, _) in &expanded {
        if !all_logical_ids.contains(&node.logical_id) {
            all_logical_ids.push(node.logical_id.clone());
        }
    }

    Ok(SearchExpandResult {
        search_hits: resolved_hits,
        expanded,
        all_logical_ids,
        degradations: Vec::new(),
    })
}

/// Slice 20 test seam — run `EXPLAIN QUERY PLAN` on the BFS CTE SQL and return
/// the plan `detail` column (column index 3) for each row. Used by
/// `explain_plan_uses_indexes` to assert index usage.
#[cfg(any(test, feature = "test-hooks"))]
pub(crate) fn explain_graph_neighbors_in_tx(
    reader: &mut Connection,
    root_logical_id: &str,
    depth: u32,
    direction: TraversalDirection,
    scope: &ScopePredicate,
    attribution: &Arc<WalAttributionCollector>,
    worker_idx: usize,
) -> rusqlite::Result<Vec<String>> {
    // The EXPLAIN index-usage gate measures the DEFAULT (strict) read path.
    let view = ReadView::default();
    let frozen = view.freeze();
    let now = frozen.now_param().expect("the strict view always binds a validity instant");
    let mut binds = vec![
        rusqlite::types::Value::Text(root_logical_id.to_string()),
        rusqlite::types::Value::Integer(depth as i64),
        rusqlite::types::Value::Integer(now),
        rusqlite::types::Value::Integer(frozen.edge_now()),
    ];
    let bfs_sql = build_bfs_sql(direction, &view, scope, &mut binds);
    let explain_sql = format!("EXPLAIN QUERY PLAN {bfs_sql}");
    let tx = begin_attributed_reader_tx(reader, attribution, worker_idx)?;
    let mut statement = tx.prepare(&explain_sql)?;
    let rows = statement
        .query_map(rusqlite::params_from_iter(binds.iter()), |row| row.get::<_, String>(3))?;
    let mut out = Vec::new();
    for row in rows {
        out.push(row?);
    }
    Ok(out)
}
