pub(crate) enum SearchExpandHandlerError {
    Sqlite(rusqlite::Error),
    FrozenRead(FrozenReadError),
    InvalidFilter(String),
}

impl From<rusqlite::Error> for SearchExpandHandlerError {
    fn from(error: rusqlite::Error) -> Self {
        Self::Sqlite(error)
    }
}

impl From<SnapshotFilterError> for SearchExpandHandlerError {
    fn from(error: SnapshotFilterError) -> Self {
        match error {
            SnapshotFilterError::Sqlite(error) => Self::Sqlite(error),
            SnapshotFilterError::InvalidFilter(reason) => Self::InvalidFilter(reason),
        }
    }
}

/// Slice 20 (G6) — result of [`Engine::search_expand`]: initial search hits
/// plus nodes reached by bounded BFS expansion that are not already in the
/// search hit set.
///
/// Another crate cannot build it with a struct expression:
///
/// ```compile_fail,E0639
/// let _ = fathomdb_engine::SearchExpandResult {
///     search_hits: Vec::new(),
///     expanded: Vec::new(),
///     all_logical_ids: Vec::new(),
///     degradations: Vec::new(),
/// };
/// ```
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct SearchExpandResult {
    /// Original RRF-scored search results (G1+G9 hybrid).
    pub search_hits: Vec<SearchHit>,
    /// Nodes reached by graph traversal but NOT already in `search_hits`.
    /// Each entry is `(node, hop_count)` where `hop_count` is the BFS depth
    /// from the nearest search hit that reached this node.
    pub expanded: Vec<(NodeRecord, u32)>,
    /// Deduplicated union of all logical_ids (search hits first, then expanded).
    pub all_logical_ids: Vec<String>,
    /// Requested search arms that did not run; same contract as
    /// [`SearchResult::degradations`](crate::SearchResult::degradations).
    pub degradations: Vec<ArmDegradation>,
}

